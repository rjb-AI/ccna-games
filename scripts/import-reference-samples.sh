#!/usr/bin/env bash
# Import real device output samples into reference/outputs/ (CLAUDE.md rule 3).
# Sources are pinned commits of two Apache-2.0 projects whose test suites hold raw output
# captured from real devices:
#   - networktocode/ntc-templates: tests/<platform>/<command>/*.raw (+ parsed .yml) and the
#     TextFSM template that parses each command (used to validate our generated output).
#   - CiscoTestAutomation/genieparser: iosxe golden outputs for commands ntc-templates lacks.
# Re-run to refresh: bash scripts/import-reference-samples.sh
set -euo pipefail

NTC_SHA=06fa33389fbcca31cd59aac5fd5cb2ce5c900939
GENIE_SHA=f11ee1199f7a8ef5221b94d1287b19864c68324b

NTC_COMMANDS=(
  cisco_ios/show_ip_route cisco_ios/show_ipv6_route cisco_ios/show_ip_interface_brief
  cisco_ios/show_ipv6_interface_brief cisco_ios/show_interfaces cisco_ios/show_ip_ospf_neighbor
  cisco_ios/show_standby_brief cisco_ios/show_standby cisco_ios/show_vrrp_brief
  cisco_ios/show_ip_nat_translations cisco_ios/show_access-list cisco_ios/show_ipv6_access-lists
  cisco_ios/show_spanning-tree cisco_ios/show_spanning-tree_root cisco_ios/show_etherchannel_summary
  cisco_ios/show_cdp_neighbors cisco_ios/show_cdp_neighbors_detail cisco_ios/show_lldp_neighbors
  cisco_ios/show_lldp_neighbors_detail cisco_ios/show_mac-address-table cisco_ios/show_vlan
  cisco_ios/show_port-security_interface_interface cisco_ios/show_logging cisco_ios/show_ip_arp
  cisco_ios/show_ipv6_neighbors cisco_ios/show_ip_dhcp_binding cisco_ios/show_ip_dhcp_snooping_binding
  cisco_ios/show_version cisco_ios/show_snmp_community
  linux/ip_address_show linux/ip_route_show linux/arp_-a
)
GENIE_PARSERS=(
  ShowPortSecurity ShowPortSecurityInterface ShowPortSecurityAddress ShowInterfacesTrunk
  ShowEtherchannelSummary ShowSpanningTree ShowIpInterfaceBrief ShowLogging
)

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/reference/outputs"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

fetch() { # repo sha dir
  git init -q "$3"
  git -C "$3" remote add origin "https://github.com/$1.git"
  git -C "$3" fetch -q --depth 1 --filter=blob:none origin "$2"
  git -C "$3" sparse-checkout set --no-cone "${@:4}"
  git -C "$3" checkout -q FETCH_HEAD
}

ntc_paths=(/LICENSE)
for c in "${NTC_COMMANDS[@]}"; do
  ntc_paths+=("/tests/$c/" "/ntc_templates/templates/${c%%/*}_${c#*/}.textfsm")
done
fetch networktocode/ntc-templates "$NTC_SHA" "$TMP/ntc" "${ntc_paths[@]}"

genie_paths=(/LICENSE)
for p in "${GENIE_PARSERS[@]}"; do genie_paths+=("/src/genie/libs/parser/iosxe/tests/$p/cli/equal/"); done
fetch CiscoTestAutomation/genieparser "$GENIE_SHA" "$TMP/genie" "${genie_paths[@]}"

rm -rf "$OUT/ntc-templates" "$OUT/genieparser"
for c in "${NTC_COMMANDS[@]}"; do
  dest="$OUT/ntc-templates/$c"
  mkdir -p "$dest"
  cp "$TMP/ntc/tests/$c/"*.raw "$TMP/ntc/tests/$c/"*.yml "$dest/"
  tpl="$TMP/ntc/ntc_templates/templates/${c%%/*}_${c#*/}.textfsm"
  [[ -f "$tpl" ]] && cp "$tpl" "$dest/template.textfsm"
done
cp "$TMP/ntc/LICENSE" "$OUT/ntc-templates/LICENSE"

for p in "${GENIE_PARSERS[@]}"; do
  dest="$OUT/genieparser/iosxe/$p"
  mkdir -p "$dest"
  cp "$TMP/genie/src/genie/libs/parser/iosxe/tests/$p/cli/equal/"*_output.txt "$dest/"
done
cp "$TMP/genie/LICENSE" "$OUT/genieparser/LICENSE"

cat > "$OUT/SOURCES.md" <<MD
# Where these samples come from

Generated by \`scripts/import-reference-samples.sh\`. Do not edit the imported folders by hand.

| Folder | Source | Licence |
|---|---|---|
| \`ntc-templates/\` | [networktocode/ntc-templates](https://github.com/networktocode/ntc-templates/tree/$NTC_SHA) test suite: \`.raw\` is real device output, \`.yml\` is what the parser extracts, \`template.textfsm\` is the parser | Apache-2.0 (\`ntc-templates/LICENSE\`) |
| \`genieparser/\` | [CiscoTestAutomation/genieparser](https://github.com/CiscoTestAutomation/genieparser/tree/$GENIE_SHA) iosxe golden outputs | Apache-2.0 (\`genieparser/LICENSE\`) |
| \`*.md\` at the top level | Cisco and vendor documentation pages, copied with the URL in each file's header, plus the page's field descriptions | Quoted for reference |

Some captures come from real networks and are written by the projects' contributors, so
addresses and names in them are not ours to reuse as-is: generators copy the *format*, and fill in
their own values from the core simulators.
MD
echo "Imported into $OUT"
